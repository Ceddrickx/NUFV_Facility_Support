"""Turns the database workbook into the data files the site loads.

  database/NU_Facility_Support_DB.xlsx   ->   js/data/*.js

Usage
  python tools/build-data.py                    rebuild the site's data files from the workbook
  python tools/build-data.py --reanchor         first move every date in the workbook forward so the newest
                                                activity is "now", then rebuild (use before a demo)
  python tools/build-data.py --reanchor 2026-11-02T08:00:00Z     same, but anchored to the given moment
  python tools/build-data.py --db other.xlsx    use a different workbook

The workbook is checked first (tools/validate-db.py); nothing is written when it has broken links.
Files written whole: seed-users.js, seed-tickets.js, seed-schedules.js, seed-notifications.js.
Files where only the part between GENERATED:BEGIN and GENERATED:END is replaced: constants.js, accounts.js, seed-locations.js.
Needs openpyxl:  pip install openpyxl
"""
import datetime as dt
import importlib.util
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import dbio  # noqa: E402

DATA_DIR = os.path.join(ROOT, 'js', 'data')
DEFAULT_DB = os.path.join(ROOT, 'database', 'NU_Facility_Support_DB.xlsx')
BANNER = ('/* GENERATED by tools/build-data.py from database/NU_Facility_Support_DB.xlsx.\n'
          '   Do not edit by hand: change the workbook, then run the converter again. */\n')


def js(value, indent=2):
    return json.dumps(value, ensure_ascii=False, indent=indent)


def ms(text):
    return dbio.parse_iso(text)


def put(d, key, value, keep_null=False):
    """Adds key unless the cell was blank (or adds null when keep_null)."""
    if value is None and not keep_null:
        return
    d[key] = value


# ------------------------------------------------------------------ shaping: workbook rows -> objects the site expects
def users(db):
    return [dict(id=u['id'], name=u['display_name'], welcomeName=u['welcome_name'], firstName=u['first_name'],
                 lastName=u['last_name'], fullName=u['full_name'], role=u['role'], roleLabel=u['role_label'], department=u['department'],
                 email=u['email'], status=u['status'], lastActivity=ms(u['last_activity_at']),
                 usualLocationId=u['usual_location_id']) for u in db['User']]


def accounts(db):
    by = {u['id']: u for u in db['User']}
    out = []
    for a in db['Account']:
        u = by[a['user_id']]
        o = dict(email=a['email'], password=a['password'], role=a['role'], roleLabel=a['role_label'], userId=a['user_id'],
                 name=u['first_name'], firstName=u['first_name'], lastName=u['last_name'],
                 fullName=f"{u['first_name']} {u['last_name']}")
        put(o, 'mfaSecret', a['mfa_secret'])
        out.append(o)
    return out


def locations(db):
    out = []
    for l in db['Location']:
        o = dict(id=l['id'], building=l['building'], floor=l['floor'], room=l['room'], name=l['name'], type=l['type'],
                 status=l['status'], qrPayload=l['qr_payload'])
        if l['is_retired']:
            o['retired'] = True
        out.append(o)
    return out


def tickets(db):
    tl, att, notes = {}, {}, {}
    for e in sorted(db['TicketTimeline'], key=lambda e: (e['ticket_id'], e['sequence'])):
        tl.setdefault(e['ticket_id'], []).append(dict(status=e['status_id'], at=ms(e['at']), byId=e['by_user_id']))
    for a in db['TicketAttachment']:
        att.setdefault(a['ticket_id'], []).append(dict(id=a['id'], kind=a['kind'], name=a['name'], size=a['size_bytes'],
                                                      mime=a['mime'], addedById=a['added_by_id'], addedAt=ms(a['added_at'])))
    for n in db['TicketNote']:
        notes.setdefault(n['ticket_id'], []).append(dict(id=n['id'], authorId=n['author_id'], text=n['text'],
                                                        visibility=n['visibility'], createdAt=ms(n['created_at'])))
    out = []
    for t in db['Ticket']:
        o = {'id': t['id']}
        put(o, 'legacyFixedId', t['legacy_fixed_id'])
        o.update(title=t['title'], description=t['description'], category=t['category_id'], problemType=t['problem_type'],
                 group=t['team_id'], groupCode=t['group_code'], status=t['status_id'], locationId=t['location_id'],
                 reporterId=t['reporter_id'], assigneeId=t['assignee_id'], assignedTeam=t['assigned_team'],
                 createdAt=ms(t['created_at']), updatedAt=ms(t['updated_at']), reopenCount=t['reopen_count'],
                 attachments=att.get(t['id'], []), notes=notes.get(t['id'], []), timeline=tl[t['id']])
        put(o, 'legacyTicketNo', t['legacy_ticket_no'])
        o.update(ticketNo=t['id'], ticketId=t['internal_id'], ticketYear=t['year'], ticketSeq=t['sequence'])
        put(o, 'resolvedAt', ms(t['resolved_at']))
        put(o, 'resolutionNote', t['resolution_note'])
        put(o, 'closedAt', ms(t['closed_at']))
        put(o, 'feedback', t['feedback'])
        out.append(o)
    return out


def schedules(db):
    out = []
    for s in db['Schedule']:
        o = dict(id=s['id'], kind=s['kind'])
        put(o, 'ticketId', s['ticket_id'])
        o['locationId'] = s['location_id']
        put(o, 'title', s['title'])
        put(o, 'courseCode', s['course_code'])
        put(o, 'weekday', s['weekday'])
        put(o, 'date', s['scheduled_date'])
        o.update(start=s['start_time'], end=s['end_time'])
        out.append(o)
    return out


def notifications(db):
    out = []
    for n in db['Notification']:
        o = dict(id=n['id'], userId=n['user_id'], type=n['type'], message=n['message'], read=bool(n['is_read']),
                 createdAt=ms(n['created_at']))
        put(o, 'scheduleId', n['schedule_id'])
        put(o, 'ticketId', n['ticket_id'])
        out.append(o)
    return out


def audit_log(db):
    return [dict(id=a['id'], at=ms(a['at']), actorId=a['actor_id'], action=a['action'], ticketId=a['ticket_id'],
                 details=a['details'] or '') for a in db['AuditLog']]


def counters(db):
    return {c['id']: c['value'] for c in db['Counter']}


def lookups(db, stamp):
    cfg = {c['id']: c['value'] for c in db['Config']}
    probs = {}
    for p in sorted(db['ProblemType'], key=lambda p: p['sort_order']):
        probs.setdefault(p['category_id'], []).append(dict(label=p['label'], title=p['title'] or '', safety=bool(p['is_safety'])))
    cats = []
    for c in sorted(db['Category'], key=lambda c: c['sort_order']):
        o = dict(id=c['id'], label=c['label'], group=c['team_id'], icon=c['icon'], problems=probs.get(c['id'], []))
        if c['requires_no_password']:
            o['noPassword'] = True
        cats.append(o)
    roles = {r['id']: dict(label=r['label'], short=r['short_label']) for r in sorted(db['Role'], key=lambda r: r['sort_order'])}
    return dict(
        meta=dict(source='database/NU_Facility_Support_DB.xlsx', generatedAt=stamp, dataAnchor=cfg.get('data_anchor_at')),
        config=dict(defaultRole=cfg['default_role'], defaultUserId=cfg['default_user_id'],
                    microsoftSignInEmail=cfg['microsoft_signin_email'], defaultLocationId=cfg['default_location_id'], recurringThreshold=int(cfg['recurring_threshold'])),
        ROLES=roles,
        STATUS=[s['id'] for s in sorted(db['Status'], key=lambda s: s['display_order'])],
        STATUS_ORDER=[s['id'] for s in sorted(db['Status'], key=lambda s: s['workflow_order'])],
        GROUPS=[t['id'] for t in sorted(db['Team'], key=lambda t: t['sort_order'])],
        LOCATION_TYPES=[t['id'] for t in sorted(db['LocationType'], key=lambda t: t['sort_order'])],
        NO_PASSWORD=cfg['no_password_text'], SAFETY_TEXT=cfg['safety_text'], CATEGORIES=cats)


def location_parts(db):
    kinds = [dict(value=k['id'], label=k['label'], field=k['field_label']) for k in sorted(db['LocationKind'], key=lambda k: k['sort_order'])]
    kind_of = {t['id']: t['kind_id'] for t in db['LocationType']}
    floors = {}
    for f in sorted(db['BuildingFloor'], key=lambda f: f['sort_order']):
        floors.setdefault(f['building'], []).append(f['floor'])
    remap = {a['id']: a['location_id'] for a in db['LocationAlias']}
    return kinds, kind_of, floors, remap


# ------------------------------------------------------------------ writing files
def write(name, text):
    with open(os.path.join(DATA_DIR, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def fill_region(name, region, body):
    path = os.path.join(DATA_DIR, name)
    text = open(path, encoding='utf-8').read()
    pat = re.compile(r'(/\* GENERATED:BEGIN %s \*/\n).*?(\n[ \t]*/\* GENERATED:END %s \*/)' % (region, region), re.S)
    if not pat.search(text):
        raise SystemExit(f'{name} has no GENERATED:BEGIN {region} / GENERATED:END {region} markers')
    write(name, pat.sub(lambda m: m.group(1) + body + m.group(2), text, count=1))


def indent(text, n):
    pad = ' ' * n
    return '\n'.join(pad + line if line else line for line in text.split('\n'))


def build(db, stamp):
    L = lookups(db, stamp)
    fill_region('constants.js', 'db', indent('const DB = ' + js(L) + ';', 2))
    fill_region('accounts.js', 'list', indent('const list = ' + js(accounts(db)) + ';', 2))
    kinds, kind_of, floors, remap = location_parts(db)
    fill_region('seed-locations.js', 'locations', indent(
        'const LOCATION_KINDS = ' + js(kinds) + ';\n'
        'const KIND_BY_TYPE = ' + js(kind_of) + ';\n'
        'const BUILDING_FLOOR_LIST = ' + js(floors) + ';\n'
        'const LOCATION_REMAP = ' + js(remap) + ';\n'
        'const LOCATIONS = ' + js(locations(db)) + ';', 2))
    write('seed-users.js', BANNER + '/* People. Four roles: student, fmo, it, admin. Faculty use the student role and keep the "Faculty" role label. */\n'
          '(function () {\n  const App = (window.App = window.App || {});\n  App.seed = App.seed || {};\n\n'
          '  App.seed.users = function () {\n    return ' + indent(js(users(db)), 4).lstrip() + ';\n  };\n})();\n')
    write('seed-tickets.js', BANNER + '/* Tickets, the ticket-number counters and the audit log. */\n'
          '(function () {\n  const App = (window.App = window.App || {});\n  App.seed = App.seed || {};\n\n'
          '  App.seed.tickets = function () {\n    return ' + indent(js(tickets(db)), 4).lstrip() + ';\n  };\n\n'
          '  App.seed.counters = function () {\n    return ' + indent(js(counters(db)), 4).lstrip() + ';\n  };\n\n'
          '  App.seed.auditLog = function () {\n    return ' + indent(js(audit_log(db)), 4).lstrip() + ';\n  };\n})();\n')
    write('seed-schedules.js', BANNER + '/* Weekly class slots (kind "class") and dated ticket visits (kind "ticket"). */\n'
          '(function () {\n  const App = (window.App = window.App || {});\n  App.seed = App.seed || {};\n\n'
          '  App.seed.schedules = function () {\n    return ' + indent(js(schedules(db)), 4).lstrip() + ';\n  };\n})();\n')
    write_accounts_txt(db)
    write('seed-notifications.js', BANNER + '/* In-app notifications. */\n'
          '(function () {\n  const App = (window.App = window.App || {});\n  App.seed = App.seed || {};\n\n'
          '  App.seed.notifications = function () {\n    return ' + indent(js(notifications(db)), 4).lstrip() + ';\n  };\n})();\n')


def write_accounts_txt(db):
    users = {u['id']: u for u in db['User']}
    groups = [('ADMIN', lambda a: a['role'] == 'admin' and not a['mfa_secret']),
              ('IT TECHNICIANS', lambda a: a['role'] == 'it' and not a['mfa_secret']),
              ('FMO TECHNICIANS', lambda a: a['role'] == 'fmo' and not a['mfa_secret']),
              ('STUDENTS', lambda a: a['role'] == 'student' and a['role_label'] == 'Student' and not a['mfa_secret']),
              ('FACULTY', lambda a: a['role_label'] == 'Faculty' and not a['mfa_secret'])]
    out = ['NU FAIRVIEW - ACCOUNTS FOR MANUAL SIGN-IN', '=' * 41,
           'Demo only. This file is written by tools/build-data.py from the Account sheet of database/NU_Facility_Support_DB.xlsx.',
           'Passwords are plain text. Type the full email and the password exactly. Email letter case does not matter; the password must match exactly.', '']
    for title, pick in groups:
        rows = [a for a in db['Account'] if pick(a)]
        if not rows:
            continue
        out += [f'{title} ({len(rows)})', '-' * 65]
        out += [f"{users[a['user_id']]['full_name']:<26}{a['email']:<46}{a['password']}" for a in rows]
        out.append('')
    for a in [a for a in db['Account'] if a['mfa_secret']]:
        out += ['TWO-STEP SIGN-IN ACCOUNT (1)', '-' * 65,
                f"{users[a['user_id']]['full_name']} ({a['role_label']} account)", f"Email:     {a['email']}", f"Password:  {a['password']}",
                'Also asks for a 6-digit Google Authenticator code every time.',
                f"Authenticator setup key (tap +, then \"Enter a setup key\"): {a['mfa_secret']}"]
    with open(os.path.join(ROOT, 'ACCOUNTS.txt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


def reanchor(db, target_ms):
    cfg = {c['id']: c for c in db['Config']}
    delta = target_ms - ms(cfg['data_anchor_at']['value'])
    days = round(delta / 86400000)
    cols = {'User': ['last_activity_at'], 'Ticket': ['created_at', 'updated_at', 'resolved_at', 'closed_at'],
            'TicketTimeline': ['at'], 'TicketAttachment': ['added_at'], 'TicketNote': ['created_at'],
            'Notification': ['created_at'], 'AuditLog': ['at']}
    for sheet, names in cols.items():
        for r in db[sheet]:
            for c in names:
                if r[c]:
                    r[c] = dbio.iso(ms(r[c]) + delta)
    for s in db['Schedule']:
        if s['scheduled_date']:
            s['scheduled_date'] = (dt.date.fromisoformat(s['scheduled_date']) + dt.timedelta(days=days)).isoformat()
    cfg['data_anchor_at']['value'] = dbio.iso(target_ms)
    return days


def main():
    args = sys.argv[1:]
    path = DEFAULT_DB
    if '--db' in args:
        path = os.path.abspath(args[args.index('--db') + 1])
    db = dbio.read_workbook(path)
    spec = importlib.util.spec_from_file_location('validate_db', os.path.join(HERE, 'validate-db.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    errs = mod.check(db)
    if errs:
        for e in errs:
            print('PROBLEM:', e)
        raise SystemExit(f'{len(errs)} problem(s) in the workbook. Nothing was changed.')
    now = int(dt.datetime.now(dt.timezone.utc).timestamp() * 1000)
    if '--reanchor' in args:
        i = args.index('--reanchor')
        target = ms(args[i + 1]) if i + 1 < len(args) and not args[i + 1].startswith('--') else now
        days = reanchor(db, target)
        dbio.write_workbook(path, db)
        print(f'Dates in the workbook moved forward by {days} day(s). Message texts that name a date are not changed.')
    build(db, dbio.iso(now))
    print('Site data rebuilt from', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
